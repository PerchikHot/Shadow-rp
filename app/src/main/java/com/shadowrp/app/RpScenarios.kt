package com.shadowrp.app

/** Optional story starters; changing a scenario never rewrites chat history. */
internal object RpScenarios {
    val templates: List<Pair<String, String>> = listOf(
        "Ночная станция" to "Заброшенная станция на окраине города оживает после полуночи. Игрок и персонаж находят старое сообщение, которое меняет их планы. Начни с описания обстановки и предложи выбор действий.",
        "Сигнал из космоса" to "Корабль получает неизвестный сигнал из туманности. Игрок и персонаж исследуют источник, принимая решения вместе. Сохраняй причинно-следственные связи и не решай за игрока.",
        "Академия магии" to "Первый день в академии магии: загадочное испытание, незнакомые союзники и скрытая библиотека. Персонаж реагирует на решения игрока, но не управляет им.",
        "Детективное дело" to "В дождливом городе исчез важный свидетель. Игрок и персонаж расследуют дело, собирают улики и проверяют версии. Не раскрывай развязку раньше времени.",
    )

    fun choose(index: Int): Pair<String, String> =
        templates.getOrNull(index) ?: throw IllegalArgumentException("Unknown scenario")
}
